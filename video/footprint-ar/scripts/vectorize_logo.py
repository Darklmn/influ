"""Vectorize the Trading Evolution logo (JPG) into animatable SVG path parts.

Outputs:
  src/logoPaths.ts   -> path data for every part of the logo (emblem bars, wordmark, swoosh)
  public/logo.png    -> transparent, tightly-cropped PNG of the full logo
  public/emblem.png  -> transparent PNG of the TE emblem only

Usage: python3 scripts/vectorize_logo.py path/to/logo.jpg
"""
import json
import sys
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

SCALE = 4  # supersample before thresholding for smooth edges
ROOT = Path(__file__).resolve().parent.parent

src = sys.argv[1]
img = cv2.imread(src, cv2.IMREAD_COLOR)  # BGR
h, w = img.shape[:2]
big = cv2.resize(img, (w * SCALE, h * SCALE), interpolation=cv2.INTER_CUBIC)
big = cv2.GaussianBlur(big, (0, 0), SCALE * 0.6)
b, g, r = [big[:, :, i].astype(np.int32) for i in range(3)]

lum = (0.299 * r + 0.587 * g + 0.114 * b)
blue_mask = ((b - r) > 90) & ((b - g) > 50)
black_mask = (lum < 128) & ~blue_mask


def contours_to_path(mask):
    m = (mask.astype(np.uint8)) * 255
    cnts, hier = cv2.findContours(m, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    return cnts, hier


def poly_d(cnt):
    eps = 0.35 * SCALE
    approx = cv2.approxPolyDP(cnt, eps, True).reshape(-1, 2) / SCALE
    if len(approx) < 3:
        return ""
    pts = " ".join(f"{x:.1f} {y:.1f}" for x, y in approx)
    return f"M{pts}Z"


def components(mask, color):
    cnts, hier = contours_to_path(mask)
    out = []
    if hier is None:
        return out
    hier = hier[0]
    for i, c in enumerate(cnts):
        if hier[i][3] != -1:
            continue  # hole; handled by its parent
        area = cv2.contourArea(c) / (SCALE * SCALE)
        if area < 30:
            continue
        d = poly_d(c)
        child = hier[i][2]
        while child != -1:
            if cv2.contourArea(cnts[child]) / (SCALE * SCALE) > 4:
                d += poly_d(cnts[child])
            child = hier[child][0]
        x, y, bw, bh = cv2.boundingRect(c)
        out.append({
            "color": color,
            "d": d,
            "x": x / SCALE, "y": y / SCALE, "w": bw / SCALE, "h": bh / SCALE,
            "area": area,
        })
    return out


parts = components(black_mask, "black") + components(blue_mask, "blue")

emblem = [p for p in parts if p["y"] < 680]
word = [p for p in parts if 680 <= p["y"] and not (p["color"] == "blue" and p["w"] > 200)]
swoosh = [p for p in parts if p["color"] == "blue" and p["w"] > 200 and p["y"] > 680]

emblem.sort(key=lambda p: (p["y"], p["x"]))
# Name emblem pieces: T (largest black), E top / E mid (blue) / E bottom
T = max([p for p in emblem if p["color"] == "black"], key=lambda p: p["area"])
rest = [p for p in emblem if p is not T]
rest.sort(key=lambda p: p["y"])
names = ["eTop", "eMid", "eBot"]
emblem_named = {"T": T}
for n, p in zip(names, rest):
    emblem_named[n] = p

word.sort(key=lambda p: p["x"])
# The bold "Trading" sits left of the light "Evolution"; split at the largest x-gap.
xs = [p["x"] for p in word]
gaps = [(word[i + 1]["x"] - (word[i]["x"] + word[i]["w"]), i) for i in range(len(word) - 1)]
split = max(gaps)[1]
trading = word[: split + 1]
evolution = word[split + 1:]


def bbox(ps):
    x0 = min(p["x"] for p in ps)
    y0 = min(p["y"] for p in ps)
    x1 = max(p["x"] + p["w"] for p in ps)
    y1 = max(p["y"] + p["h"] for p in ps)
    return {"x": x0, "y": y0, "w": x1 - x0, "h": y1 - y0}


allparts = list(emblem_named.values()) + word + swoosh
full_box = bbox(allparts)
emblem_box = bbox(list(emblem_named.values()))

ts = {
    "viewBox": [full_box["x"], full_box["y"], full_box["w"], full_box["h"]],
    "emblemBox": [emblem_box["x"], emblem_box["y"], emblem_box["w"], emblem_box["h"]],
    "emblem": {k: {"d": v["d"], "color": v["color"], "box": [v["x"], v["y"], v["w"], v["h"]]}
               for k, v in emblem_named.items()},
    "trading": [{"d": p["d"], "box": [p["x"], p["y"], p["w"], p["h"]]} for p in trading],
    "evolution": [{"d": p["d"], "box": [p["x"], p["y"], p["w"], p["h"]]} for p in evolution],
    "swoosh": {"d": swoosh[0]["d"], "box": [swoosh[0]["x"], swoosh[0]["y"], swoosh[0]["w"], swoosh[0]["h"]]},
}

# Sample the exact brand colours from the source image
rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
small_blue = ((rgb[:, :, 2].astype(int) - rgb[:, :, 0]) > 150)
small_black = rgb.sum(axis=2) < 60
blue = np.median(rgb[small_blue], axis=0).astype(int)
black = np.median(rgb[small_black], axis=0).astype(int)
ts["colors"] = {
    "blue": "#%02X%02X%02X" % tuple(blue),
    "black": "#%02X%02X%02X" % tuple(black),
}

out = ROOT / "src" / "logoPaths.ts"
out.write_text(
    "// Auto-generated by scripts/vectorize_logo.py from the official Trading Evolution logo.\n"
    "// Do not edit by hand.\n"
    f"export const LOGO = {json.dumps(ts, ensure_ascii=False)} as const;\n"
)
print("parts:", {k: len(v) if isinstance(v, list) else 1 for k, v in ts.items()})
print("colors:", ts["colors"], "viewBox", ts["viewBox"])

# Transparent PNGs (alpha from darkness / blueness), cropped
pil = Image.open(src).convert("RGB")
a = np.asarray(pil).astype(np.float32)
lum_s = 0.299 * a[:, :, 0] + 0.587 * a[:, :, 1] + 0.114 * a[:, :, 2]
alpha = np.clip((250 - lum_s) / (250 - 140) * 255, 0, 255)
bl = (a[:, :, 2] - a[:, :, 0]) > 60
alpha[bl] = np.clip((a[:, :, 2] - a[:, :, 0])[bl] / 200 * 255, 0, 255)
rgba = np.dstack([a, alpha]).astype(np.uint8)
# un-premultiply against white so edges stay crisp on white backgrounds
png = Image.fromarray(rgba, "RGBA")
pad = 6
fb = full_box
png.crop((int(fb["x"]) - pad, int(fb["y"]) - pad, int(fb["x"] + fb["w"]) + pad, int(fb["y"] + fb["h"]) + pad)).save(ROOT / "public" / "logo.png")
eb = emblem_box
png.crop((int(eb["x"]) - pad, int(eb["y"]) - pad, int(eb["x"] + eb["w"]) + pad, int(eb["y"] + eb["h"]) + pad)).save(ROOT / "public" / "emblem.png")
print("wrote", out)
